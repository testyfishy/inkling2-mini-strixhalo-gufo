#!/usr/bin/env python3
"""Writes extension/src/unicode_tables.inc: the Unicode general categories the
tokenizer's splitting rule reads, as sorted ranges {first, last, class}.

Classes: 1 Lu, 2 Ll, 3 Lt, 4 Lm, 5 Lo, 6 M (Mn, Mc, Me), 7 N (Nd, Nl, No).
Code points in no range are class 0.

    python3 scripts/gen-unicode-tables.py > extension/src/unicode_tables.inc
"""
import sys
import unicodedata

CLASS = {"Lu": 1, "Ll": 2, "Lt": 3, "Lm": 4, "Lo": 5,
         "Mn": 6, "Mc": 6, "Me": 6, "Nd": 7, "Nl": 7, "No": 7}

ranges = []
start = None
current = 0
for cp in range(0x110000 + 1):
    cls = CLASS.get(unicodedata.category(chr(cp)), 0) if cp < 0x110000 else -1
    if cls != current:
        if current > 0:
            ranges.append((start, cp - 1, current))
        start, current = cp, cls

out = sys.stdout
out.write("// Generated by scripts/gen-unicode-tables.py from Unicode %s. Do not edit.\n"
          % unicodedata.unidata_version)
out.write("// {first, last, class}: 1 Lu, 2 Ll, 3 Lt, 4 Lm, 5 Lo, 6 M, 7 N.\n")
line = ""
for first, last, cls in ranges:
    item = "{0x%X,0x%X,%d}," % (first, last, cls)
    if len(line) + len(item) > 96:
        out.write(line + "\n")
        line = ""
    line += item
if line:
    out.write(line + "\n")
sys.stderr.write("%d ranges\n" % len(ranges))
